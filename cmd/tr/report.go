package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/pnathan/translations/internal/corpus"
	"github.com/pnathan/translations/internal/llm"
	"github.com/pnathan/translations/internal/work"
)

// reviewReport writes works/WORK/review.md: the patch counts of every review,
// the verdicts on the normative commentators, and every open question.
func reviewReport(cfg *work.Config) error {
	e, err := loadEnv(cfg)
	if err != nil {
		return err
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# %s: review report\n\n", cfg.Title)
	b.WriteString("Generated by `tr report` from `stage/review/*.json`.\n\n")
	b.WriteString("| unit | refs | translator | error | question | style | morph | contradicts |\n|---|---|---|---|---|---|---|---|\n")
	total := map[string]int{}
	var questions []string
	for _, u := range e.Corpus.Units {
		var ru llm.ReviewUnit
		var tu llm.TranslationUnit
		if corpus.ReadJSON(llm.ReviewPath(cfg, u.ID), &ru) != nil {
			fmt.Fprintf(&b, "| %s | %s–%s | — | not reviewed |||||\n", u.ID, u.Refs[0], u.Refs[len(u.Refs)-1])
			continue
		}
		corpus.ReadJSON(llm.TranslationPath(cfg, u.ID), &tu)
		n := map[string]int{}
		for _, p := range ru.Patches {
			n[p.Severity]++
			if strings.HasPrefix(p.Path, "morph:") {
				n["morph"]++
			}
			if p.Severity == "question" {
				questions = append(questions, fmt.Sprintf("- **%s %s** `%s`: %s", u.ID, p.Ref, p.Path, oneLine(p.Reason)))
			}
		}
		for _, v := range ru.Verdicts {
			if v.Verdict == "contradicts" {
				n["contradicts"]++
			}
		}
		for k, v := range n {
			total[k] += v
		}
		fmt.Fprintf(&b, "| %s | %s–%s | %s | %d | %d | %d | %d | %d |\n", u.ID, u.Refs[0], u.Refs[len(u.Refs)-1], tu.Model,
			n["error"], n["question"], n["style"], n["morph"], n["contradicts"])
	}
	fmt.Fprintf(&b, "| **total** | | | %d | %d | %d | %d | %d |\n\n", total["error"], total["question"], total["style"], total["morph"], total["contradicts"])
	b.WriteString("A `contradicts` verdict is either fixed by a patch or left standing with the reviewer's reason (the normative commentators disagree, and the English follows one).\n\n")
	b.WriteString("## Open questions for the editor\n\nThe review patched these with its proposed fix; each is open to reversal.\n\n")
	sort.Strings(questions)
	if len(questions) == 0 {
		b.WriteString("None.\n")
	}
	b.WriteString(strings.Join(questions, "\n") + "\n")
	if err := os.WriteFile(cfg.Path("review.md"), []byte(b.String()), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "wrote %s\n", cfg.Path("review.md"))
	return nil
}

func oneLine(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if r := []rune(s); len(r) > 400 {
		s = string(r[:400]) + "…"
	}
	return s
}
